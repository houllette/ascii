  @doc "Every `{slug, module}`, sorted by slug."
  @spec all() :: [{String.t(), module()}]
  def all, do: Enum.sort(@pieces)

  @doc "Every slug, sorted."
  @spec slugs() :: [String.t()]
  def slugs, do: @pieces |> Map.keys() |> Enum.sort()

  @doc "The module for a slug."
  @spec fetch(slug :: String.t()) :: {:ok, module()} | :error
  def fetch(slug) when is_binary(slug), do: Map.fetch(@pieces, slug)
  def fetch(_slug), do: :error

  @doc "The slug of a registered module."
  @spec slug(module :: module()) :: {:ok, String.t()} | :error
  def slug(module) do
    case Enum.find(@pieces, fn {_slug, mod} -> mod == module end) do
      {slug, _} -> {:ok, slug}
      nil -> :error
    end
  end
