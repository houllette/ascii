# mix run tools/port_status.exs
#
# Writes PORT_STATUS.md: one row per upstream piece (every golden fixture),
# with its status, its average frame time from Mix.Tasks.Ascii.Perf, and
# notes from tools/port_notes.exs. A registered piece is green: the suite
# requires its golden and contract tests (see Ascii.CoverageTest). One
# with a tolerance in test/fixtures/tolerances.exs is "tolerance"; one
# marked {:blocked, why} in the notes and not registered is "blocked"; any
# other is "todo".
alias Ascii.Registry

fixtures = "test/fixtures/golden"
slugs = fixtures |> File.ls!() |> Enum.filter(&String.ends_with?(&1, ".json")) |> Enum.map(&Path.rootname/1) |> Enum.sort()

category = fn slug ->
  head = File.open!(Path.join(fixtures, slug <> ".json"), [:read], &IO.binread(&1, 4096))
  [_, category] = Regex.run(~r/"category":"(\w+)"/, head)
  category
end

{notes, _} = Code.eval_file("tools/port_notes.exs")
{tolerances, _} = Code.eval_file("test/fixtures/tolerances.exs")
registered = Map.new(Registry.all())

rows =
  for slug <- slugs do
    category = category.(slug)
    note = Map.get(notes, slug)

    {status, ms} =
      case Map.fetch(registered, slug) do
        {:ok, mod} ->
          r = Mix.Tasks.Ascii.Perf.measure(slug, mod)
          {if(Map.has_key?(tolerances, slug), do: "tolerance", else: "green"), r}

        :error ->
          {if(match?({:blocked, _}, note), do: "blocked", else: "todo"), nil}
      end

    note =
      case note do
        {:blocked, why} -> why
        nil -> ""
        text -> text
      end

    perf = if ms, do: :erlang.float_to_binary(ms.avg, decimals: 2), else: ""
    flag = if ms && ms.avg > ms.budget, do: " (budget #{ms.budget})", else: ""
    {status, "| #{slug} | #{category} | #{status} | #{perf}#{flag} | #{note} |"}
  end

counts = rows |> Enum.map(&elem(&1, 0)) |> Enum.frequencies()
summary = for s <- ["green", "tolerance", "blocked", "todo"], do: "#{s}: #{Map.get(counts, s, 0)}"

File.write!("PORT_STATUS.md", """
# Port status

Every upstream piece, at the commit in `UPSTREAM.md`. Generated by
`mix run tools/port_status.exs`; notes come from `tools/port_notes.exs`.

#{length(rows)} pieces. #{Enum.join(summary, ", ")}.

- **green**: registered, and frame-for-frame identical to upstream in every
  golden run, text and colours (`test/pieces/<slug>_test.exs`).
- **tolerance**: identical except for the cells allowed in
  `test/fixtures/tolerances.exs` (see `PORTING.md`).
- **blocked**: cannot be matched; not registered; the note says why.
- **todo**: not ported yet.

Frame times are milliseconds on average, played as upstream's
`scripts/check.ts` times them (every `1/fps` seconds for 6 s), on the machine
that generated this file. Upstream's budgets: text pieces 4 ms, scenes 10 ms;
a piece over its budget says so.

| piece | category | status | avg ms | notes |
| --- | --- | --- | --- | --- |
#{rows |> Enum.map(&elem(&1, 1)) |> Enum.join("\n")}
""")

IO.puts("PORT_STATUS.md: #{Enum.join(summary, ", ")}")
